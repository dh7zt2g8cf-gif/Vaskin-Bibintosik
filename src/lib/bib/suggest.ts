import type { Member } from "@/lib/bib/store";
import { ageGiftLines } from "@/lib/bib/people";

export type SuggestKind = "message" | "gift";

function clip(text: string) {
  const clean = text.replace(/\s+/g, " ").trim();
  if (clean.length <= 90) return clean;
  return `${clean.slice(0, 87).trim()}…`;
}

function relationLines(member: Member): string[] {
  const r = member.relation.toLowerCase().replaceAll("ё", "е");
  const n = member.name;
  if (/мам/.test(r)) {
    return [
      `${n}, привет. Как ты сегодня? Хочу услышать тебя хотя бы на пару строк.`,
      `Пишу без повода. Спасибо, что ты есть — день от этого тише.`,
    ];
  }
  if (/пап/.test(r)) {
    return [
      `${n}, привет. Как ты? Давно не разговаривали по-человечески, не по делам.`,
      `Просто так: думаю о тебе. Расскажи, как проходит неделя.`,
    ];
  }
  if (/бабуш|дедуш|баб|дед/.test(r)) {
    return [
      `${n}, здравствуй. Скучаю по твоему голосу. Как здоровье и как дом?`,
      `Хочу заехать мыслями: как ты сегодня? Можно просто «нормально» — и то тепло.`,
    ];
  }
  if (/сестр|брат/.test(r)) {
    return [
      `${n}, привет. Что у тебя нового, кроме «да нормально»?`,
      `Давно не болтали просто так. Есть пять минут на честный ответ: как ты?`,
    ];
  }
  if (/друг|подруг/.test(r)) {
    return [
      `${n}, привет. Ты всплываешь в мыслях — как ты на самом деле?`,
      `Не по делу. Просто хочу знать, что у тебя всё не в одиночку.`,
    ];
  }
  if (/жен|муж|парень|девушк/.test(r)) {
    return [
      `${n}, я рядом, даже если день шумный. Как ты? Хочу услышать не отчёт, а тебя.`,
      `Спасибо, что ты есть сегодня. Если хочешь — расскажи, чего тебе сейчас не хватает.`,
    ];
  }
  return [];
}

function giftFromNotes(member: Member): string[] {
  const blob = `${member.relation} ${member.notes}`.toLowerCase().replaceAll("ё", "е");
  const n = member.name;
  const out: string[] = [];
  if (/чай|кофе/.test(blob)) {
    out.push(`Хороший чай или кофе, который можно заварить не спеша. ${n} это оценит больше случайной вещи.`);
  }
  if (/книг|чита/.test(blob)) {
    out.push(`Книга и закладка с одной фразой от тебя. ${n} будет к ней возвращаться.`);
  }
  if (/спорт|бег|зал|йог/.test(blob)) {
    out.push(`Что-то для движения: тёплые носки, нормальная бутылка или одно занятие, куда вы пойдёте вместе.`);
  }
  if (/музык|песн|концерт/.test(blob)) {
    out.push(`Плейлист из ваших песен или билет на небольшой концерт. Для ${n} это звучит как внимание.`);
  }
  if (/сад|цвет|растен/.test(blob)) {
    out.push(`Живое: цветок в горшке или семена. ${n} будет смотреть, как это растёт.`);
  }
  if (/слад|торт|шоколад|выпеч/.test(blob)) {
    out.push(`Сладкое, но не дежурная коробка — тот вкус, который ${n} и так любит.`);
  }
  if (/путешеств|дорог|поезд/.test(blob)) {
    out.push(`Мелочь в дорогу: хорошие носки, маска для сна или открытка «вернись».`);
  }
  return out;
}

export function suggestFor(member: Member, kind: SuggestKind, turn: number) {
  const n = member.name;
  const note = member.notes.trim();

  if (kind === "gift" && note && turn % 4 === 3) {
    return `В заметке о ${n} уже есть зацепка: «${clip(note)}». Подарок лучше строить от этого, а не от витрины.`;
  }

  const pool =
    kind === "gift"
      ? [
          ...ageGiftLines(member),
          ...giftFromNotes(member),
          `Что-то тёплое и простое — плед, кружка или чай на вечер. ${n} это можно трогать руками.`,
          `Небольшая вкусная посылка: чай, мёд или то, что делят за столом, а не ставят на полку.`,
          `Короткое письмо от руки и маленькая вещь. Для ${n} слова часто важнее коробки.`,
          note
            ? `Загляни в то, что ты уже помнишь про ${n}, и выбери одну деталь. Точный маленький подарок бьёт большой общий.`
            : `Сначала допиши в карточке ${n}, что человеку важно. Тогда подарок перестанет быть угадайкой.`,
        ]
      : [
          ...relationLines(member),
          `Привет. Давно не писали друг другу — как ты?`,
          `Можно без повода: просто думаю о тебе и надеюсь, что день мягкий.`,
          `Спасибо, что ты есть. Это правда много значит.`,
          `Как твои дни? Расскажи одну хорошую мелочь, даже если она крошечная.`,
          note
            ? `Можно опереться на то, что ты помнишь: «${clip(note)}». Спроси, как с этим сейчас.`
            : `${n}, привет. Хочу услышать тебя — не новости, а как ты на самом деле.`,
        ];

  const index = ((turn % pool.length) + pool.length) % pool.length;
  return pool[index] ?? pool[0] ?? "";
}
