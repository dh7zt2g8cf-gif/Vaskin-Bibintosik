type Turn = { role: string; content: string };

function hash(seed: string) {
  let h = 0;
  for (let i = 0; i < seed.length; i++) h = (h * 33 + seed.charCodeAt(i)) >>> 0;
  return h;
}

function pick(items: string[], seed: string, previous?: string) {
  if (items.length === 0) return "";
  let index = hash(seed) % items.length;
  if (items[index] === previous) index = (index + 1) % items.length;
  return items[index] ?? items[0];
}

const CRISIS =
  /не хочу жить|суицид|покончить с собой|убить себя|самоуби|незачем жить|лучше бы меня не было/i;

function lastAssistant(history: Turn[]) {
  for (let i = history.length - 1; i >= 0; i--) {
    if (history[i]?.role === "assistant") return history[i]?.content;
  }
  return undefined;
}

export function companionReply(text: string, history: Turn[], names: string[]) {
  const raw = text.trim();
  const t = raw.toLowerCase().replaceAll("ё", "е");
  const seed = `${raw}:${history.length}`;
  const prev = lastAssistant(history);

  if (CRISIS.test(t)) {
    return "Мне важно, что эти слова здесь. Ты не один. Если совсем тяжело — позвони близкому или на телефон доверия 8-800-2000-122, круглосуточно и бесплатно. Я рядом, если хочется просто поговорить.";
  }

  if (/дурак|идиот|туп(ой|ая|ые)|мраз|ненавижу тебя|заткнись|пошел|пошла/.test(t)) {
    return pick(
      [
        "Я не отвечаю грубостью. Если злишься — скажи, что случилось. Я выслушаю.",
        "Можно резко, я не обижусь. Только давай по делу: что тебя задело?",
      ],
      seed,
      prev,
    );
  }

  const confusedBefore = history.filter(
    (m) => m.role === "user" && /не понима/.test(m.content.toLowerCase().replaceAll("ё", "е")),
  ).length;

  if (/не понимаю|непонятно|не понял|не поняла|что ты несешь/.test(t)) {
    if (confusedBefore >= 1) {
      return "Тогда совсем просто. Одной фразой: поговорить, записать дело или написать кому-то из своих?";
    }
    return "Кажется, я объясняю мутно. Что именно неясно — слово или вся мысль?";
  }

  if (/что ты умеешь|кто ты|что ты можешь|помощь|зачем ты/.test(t)) {
    return "Я Бибинтосик. Могу просто поговорить, держать заметки, напоминания и задачи, и подсказать, что написать или подарить своим. Всё остаётся только на этом устройстве.";
  }

  const mentioned = names.find((name) => {
    const n = name.trim().toLowerCase().replaceAll("ё", "е");
    return n.length >= 2 && t.includes(n);
  });
  if (mentioned) {
    return pick(
      [
        `Если на уме ${mentioned} — загляни в «Семью». Там подскажу, что написать и что подарить.`,
        `${mentioned} можно не откладывать. Пара тёплых строк лучше, чем «потом». Идеи лежат в «Семье».`,
      ],
      seed,
      prev,
    );
  }

  if (/^(привет|здравствуй|добрый|доброе|хай|хелло|ку)\b/.test(t) || t === "приветик") {
    return pick(
      [
        "Привет. Хорошо, что ты здесь. Как ты сейчас?",
        "Я здесь. Расскажи, какой сегодня день — тихий или шумный?",
        "Привет. Можно без предисловия: как ты себя чувствуешь?",
      ],
      seed,
      prev,
    );
  }

  if (/как дела|как ты|как жизнь|что нового/.test(t)) {
    return pick(
      [
        "У меня тихо и тепло, особенно когда мы разговариваем. А у тебя как настроение?",
        "Я в порядке. Мне интереснее, как ты. Честно, одним словом?",
      ],
      seed,
      prev,
    );
  }

  if (/плохо|грустн|устал|тяжело|тоска|тревог|одинок|страшно|больно/.test(t)) {
    return pick(
      [
        "Жаль, что сейчас так. Ты не один в этом. Хочешь рассказать, что случилось, или просто посидеть рядом?",
        "Это можно не тащить молча. Я рядом. С чего началось?",
        "Тяжело — уже достаточно, чтобы остановиться и выдохнуть. Я слушаю, без спешки.",
      ],
      seed,
      prev,
    );
  }

  if (/хорошо|отлично|нормально|супер|класс|радост|счастл/.test(t)) {
    return pick(
      [
        "Как хорошо это слышать. Что именно согрело день?",
        "Пусть так и держится. Расскажи одну маленькую удачу.",
      ],
      seed,
      prev,
    );
  }

  if (/спасибо|благодар/.test(t)) {
    return pick(
      [
        "Всегда. Я для этого и здесь.",
        "Не за что. Если ещё что-то нужно — я не ухожу.",
      ],
      seed,
      prev,
    );
  }

  if (/что делать|не знаю|помоги|подскажи|запутал/.test(t)) {
    return pick(
      [
        "Давай по кусочку. Что самое маленькое, что можно сделать сегодня?",
        "Расскажи чуть точнее, что беспокоит. Вместе отделим шум от одного шага.",
      ],
      seed,
      prev,
    );
  }

  if (/люблю тебя|ты милый|ты хороший|ты добрый/.test(t)) {
    return "Мне очень тепло от этого. Ты для меня важный человек, не функция.";
  }

  if (/пока|до свидания|спокойной|доброй ночи/.test(t)) {
    return pick(
      [
        "Хорошо. Береги себя. Я здесь, когда понадоблюсь.",
        "Спокойной. Пусть ночь будет тише дня.",
      ],
      seed,
      prev,
    );
  }

  if (/скучно|нечего делать/.test(t)) {
    return pick(
      [
        "Тогда без подвига: напиши одному своему человеку или вычеркни одну задачу. Хочешь, подскажу кому?",
        "Скуку можно занять болтовнёй. Что сегодня видел такого, о чём обычно никому не рассказываешь?",
      ],
      seed,
      prev,
    );
  }

  if (raw.endsWith("?")) {
    return pick(
      [
        "Хороший вопрос. Что в нём для тебя самое важное — ответ или чтобы кто-то просто услышал?",
        "Давай так: если ответить одной фразой, чего ты ждёшь от этого вопроса?",
      ],
      seed,
      prev,
    );
  }

  if (raw.length > 140) {
    return pick(
      [
        "Я прочитал до конца. Тебе важнее, чтобы тебя просто поняли, или чтобы мы нашли один следующий шаг?",
        "Слышу, это не мелочь. Какая часть из сказанного давит сильнее всего?",
      ],
      seed,
      prev,
    );
  }

  return pick(
    [
      "Я слушаю. Расскажи ещё немного — мне важно понять именно тебя.",
      "Продолжай. Я никуда не тороплюсь.",
      "Принял. Что за этим стоит — усталость, мысль или человек?",
    ],
    seed,
    prev,
  );
}
